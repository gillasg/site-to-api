import type { JsonSchema, Operation, Param, SiteModel } from "../types.js";
import { itemsSchema } from "../runtime/model-helpers.js";

// A typed TypeScript client for a mapped site: one method per operation, typed parameters and
// responses, and async iterators for every paginated operation.

function pascal(text: string): string {
  return text
    .replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, __, char: string) => char.toUpperCase())
    .replace(/^\d/, "N$&");
}

function propertyName(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function typeList(schema: JsonSchema): string[] {
  if (Array.isArray(schema.type)) return schema.type as string[];
  return schema.type ? [schema.type as string] : [];
}

/** Types that a schema states outright: references, enums, constants, unions. */
function namedType(schema: JsonSchema, depth: number): string | undefined {
  if (typeof schema.$ref === "string") return pascal(schema.$ref.split("/").pop() ?? "Unknown");
  if (Array.isArray(schema.enum))
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if ("const" in schema) return JSON.stringify(schema.const);
  const union = (schema.anyOf ?? schema.oneOf) as JsonSchema[] | undefined;
  return union?.map((item) => tsType(item, depth + 1)).join(" | ");
}

export function tsType(schema: JsonSchema | undefined, depth = 0): string {
  if (!schema || depth > 12) return "unknown";
  const named = namedType(schema, depth);
  if (named) return named;
  const types = typeList(schema);
  return types.length ? types.map((type) => single(type, schema, depth)).join(" | ") : "unknown";
}

function single(type: string, schema: JsonSchema, depth: number): string {
  if (type === "string") return "string";
  if (type === "integer" || type === "number") return "number";
  if (type === "boolean") return "boolean";
  if (type === "null") return "null";
  if (type === "array") {
    const item = tsType(schema.items as JsonSchema | undefined, depth + 1);
    return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`;
  }
  if (type === "object") return objectType(schema, depth);
  return "unknown";
}

function objectType(schema: JsonSchema, depth: number): string {
  const properties = schema.properties as Record<string, JsonSchema> | undefined;
  if (!properties) {
    const values = schema.additionalProperties as JsonSchema | undefined;
    return `Record<string, ${values ? tsType(values, depth + 1) : "unknown"}>`;
  }
  const required = new Set((schema.required as string[] | undefined) ?? []);
  const pad = "  ".repeat(depth + 1);
  const fields = Object.entries(properties).map(
    ([name, value]) =>
      `${pad}${propertyName(name)}${required.has(name) ? "" : "?"}: ${tsType(value, depth + 1)};`,
  );
  return `{\n${fields.join("\n")}\n${"  ".repeat(depth)}}`;
}

function paramsType(operation: Operation): string {
  const fields = operation.params
    .filter(
      (param) =>
        !param.constant &&
        !param.generated &&
        !operation.signing?.headers.includes(param.name) &&
        !(param.in === "header" && /^(authorization|x-csrf|x-xsrf)/i.test(param.name)),
    )
    .map(
      (param: Param) =>
        `  ${propertyName(param.name)}${param.in === "path" ? "" : "?"}: ${tsType(param.schema, 1)};`,
    );
  const body = bodyFields(operation);
  if (body) fields.push(...body);
  return `{\n${fields.join("\n")}\n}`;
}

function bodyFields(operation: Operation): string[] | undefined {
  const schema = operation.requestBody?.schema;
  if (!schema) return undefined;
  if (operation.kind === "graphql") {
    const variables = (schema.properties as Record<string, JsonSchema> | undefined)?.variables;
    return [`  variables?: ${tsType(variables, 1)};`];
  }
  const properties = schema.properties as Record<string, JsonSchema> | undefined;
  const fields = Object.entries(properties ?? {}).map(
    ([name, value]) => `  ${propertyName(name)}?: ${tsType(value, 1)};`,
  );
  return [...fields, `  body?: ${tsType(schema, 1)};`];
}

function responseType(operation: Operation): string {
  const ok = Object.entries(operation.responses).find(([status]) => status.startsWith("2"))?.[1];
  return ok?.schema ? tsType(ok.schema) : "unknown";
}

export function generateClient(model: SiteModel): string {
  const typeName = pascal(model.site.replace(/\./g, " ")) + "Api";
  const out: string[] = [
    `// Typed client for ${model.site}, generated by site-to-api. Rebuild to update it.`,
    `import { siteApi, type SiteApiOptions } from "site-to-api/runtime";`,
    "",
  ];
  for (const [name, schema] of Object.entries(model.components))
    out.push(`export type ${pascal(name)} = ${tsType(schema)};`, "");
  const methods: string[] = [];
  const pagers: string[] = [];
  for (const operation of model.operations) {
    const base = pascal(operation.id);
    out.push(
      `export type ${base}Params = ${paramsType(operation)};`,
      `export type ${base}Response = ${responseType(operation)};`,
      "",
    );
    const optional = operation.params.some((p) => p.in === "path") ? "" : "?";
    const doc = `  /** ${operation.method} ${operation.path} (${operation.bucket} confidence) */`;
    methods.push(
      doc,
      `  ${operation.id}(params${optional}: ${base}Params): Promise<${base}Response>;`,
    );
    if (operation.pagination) {
      const item = itemsSchema(model, operation);
      pagers.push(
        `    ${operation.id}(params${optional}: ${base}Params): AsyncIterable<${item ? tsType(item, 2) : "unknown"}>;`,
      );
    }
  }
  for (const page of model.pages) {
    const base = pascal(page.id);
    out.push(`export type ${base}Response = ${tsType(page.schema)};`, "");
    const params = page.params.length
      ? `params: { ${page.params.map((p) => `${propertyName(p.name)}: string`).join("; ")} }`
      : "params?: Record<string, never>";
    methods.push(
      `  /** Page ${page.path} */`,
      `  ${page.id}(${params}): Promise<${base}Response>;`,
    );
  }
  out.push(
    `export interface ${typeName} {`,
    ...methods,
    `  paginate: {`,
    ...pagers,
    `  };`,
    `  call(operationId: string, params?: Record<string, unknown>): Promise<unknown>;`,
    `}`,
    "",
    `export async function create${typeName}(options?: SiteApiOptions): Promise<${typeName}> {`,
    `  return (await siteApi(${JSON.stringify(model.site)}, options)) as unknown as ${typeName};`,
    `}`,
    "",
  );
  return out.join("\n");
}
